// Renders a mock artwork preview (SVG) for a file.
// `tint` overrides all element colors (legacy single-color mode).
// `sepState` can be an array of active separation names (legacy) or an object
// mapping separation name -> { visible: bool, opacity: 0..1 }.
window.artwork = function (file, tint, sepState) {
  var seps = file.separations || [];
  if (!seps.length) {
    var c = tint || file.brand;
    return '<svg class="v-art" viewBox="0 0 300 300" xmlns="http://www.w3.org/2000/svg">' +
      '<rect x="24" y="44" width="252" height="212" rx="18" fill="' + c + '" opacity="0.9"/>' +
      '<text x="150" y="150" text-anchor="middle" font-family="sans-serif" font-size="20" font-weight="700" fill="#ffffff">' + file.product + '</text>' +
      '<text x="150" y="178" text-anchor="middle" font-family="sans-serif" font-size="12" fill="#ffffff" opacity="0.85">' + file.dims + '</text>' +
      '</svg>';
  }

  // Legacy array support, plus new state object support.
  var isArray = Array.isArray(sepState);
  function sepOpacity(name) {
    if (sepState == null) return 1;
    if (isArray) return sepState.indexOf(name) !== -1 ? 1 : 0;
    var st = sepState[name];
    if (!st) return 0;
    if (!st.visible) return 0;
    var baseOpacity = st.opacity != null ? st.opacity : 1;
    return baseOpacity;
  }

  if (tint) {
    var simple = '<svg class="v-art" viewBox="0 0 300 300" xmlns="http://www.w3.org/2000/svg">' +
      '<rect x="24" y="44" width="252" height="212" rx="18" fill="' + tint + '" opacity="0.9"/>' +
      '<text x="150" y="150" text-anchor="middle" font-family="sans-serif" font-size="20" font-weight="700" fill="#ffffff">' + file.product + '</text>' +
      '<text x="150" y="178" text-anchor="middle" font-family="sans-serif" font-size="12" fill="#ffffff" opacity="0.85">' + file.dims + '</text>' +
      '</svg>';
    return simple;
  }

  var shapes = [
    { type: 'rect', x: 24, y: 44, w: 252, h: 212, rx: 18 },
    { type: 'rect', x: 24, y: 44, w: 252, h: 32, rx: 18 },
    { type: 'rect', x: 36, y: 120, w: 228, h: 80, rx: 10 },
    { type: 'rect', x: 36, y: 220, w: 228, h: 6, rx: 3 },
    { type: 'circle', cx: 90, cy: 160, r: 22 },
    { type: 'circle', cx: 210, cy: 160, r: 22 },
    { type: 'rect', x: 24, y: 160, w: 252, h: 24, rx: 6 },
    { type: 'circle', cx: 150, cy: 160, r: 36 }
  ];

  // Pick text color from visible Black plate, or the first visible separation.
  var textSep = null;
  for (var i = 0; i < seps.length; i++) {
    if (seps[i].name === 'Black' && sepOpacity(seps[i].name) > 0) {
      textSep = seps[i];
      break;
    }
  }
  if (!textSep) {
    for (var j = 0; j < seps.length; j++) {
      if (sepOpacity(seps[j].name) > 0) { textSep = seps[j]; break; }
    }
  }
  var textColor = textSep ? textSep.color : '#000000';
  var textOpacity = textSep ? sepOpacity(textSep.name) : 0;

  var svg = '<svg class="v-art" viewBox="0 0 300 300" xmlns="http://www.w3.org/2000/svg">';

  seps.forEach(function (s, idx) {
    var opacity = sepOpacity(s.name);
    if (opacity <= 0) return;
    var shape = shapes[idx % shapes.length];
    var baseOpacity = s.opacity != null ? s.opacity : 1;
    var effectiveOpacity = baseOpacity * opacity;
    if (shape.type === 'rect') {
      svg += '<rect x="' + shape.x + '" y="' + shape.y + '" width="' + shape.w + '" height="' + shape.h + '" rx="' + shape.rx + '" fill="' + s.color + '" opacity="' + effectiveOpacity + '"/>';
    } else if (shape.type === 'circle') {
      svg += '<circle cx="' + shape.cx + '" cy="' + shape.cy + '" r="' + shape.r + '" fill="' + s.color + '" opacity="' + effectiveOpacity + '"/>';
    }
  });

  svg += '<text x="150" y="86" text-anchor="middle" font-family="sans-serif" font-size="18" font-weight="700" fill="' + textColor + '" opacity="' + textOpacity + '">' + file.product + '</text>';
  svg += '<text x="150" y="252" text-anchor="middle" font-family="sans-serif" font-size="11" font-weight="500" fill="' + textColor + '" opacity="' + textOpacity + '">' + file.dims + '</text>';

  svg += '<rect x="24" y="44" width="252" height="212" rx="18" fill="none" stroke="#0f172a" stroke-opacity="0.15" stroke-width="2"/>';
  svg += '</svg>';
  return svg;
};

window.getFileById = function (id) {
  for (var i = 0; i < window.FILES.length; i++) {
    if (window.FILES[i].id === id) return window.FILES[i];
  }
  return null;
};
